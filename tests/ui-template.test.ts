import {describe,it,expect} from "vitest";
import {dashboardHtml} from "../src/ui/template.js";

describe("dashboard UI composition",()=>{
 it("composes the sidebar, design system, client and page shell",()=>{
  expect(dashboardHtml).toContain('id="appSidebar"');
  expect(dashboardHtml).toContain('id="themeToggle"');
  expect(dashboardHtml).toContain('id="commandOverlay"');
  expect(dashboardHtml).toContain('id="universeCanvas"');
  expect(dashboardHtml).toContain('id="tokenAdminControls"');
  expect(dashboardHtml).toContain('id="rotateAdminToken"');
  expect(dashboardHtml).toContain('id="rotateOperatorToken"');
  expect(dashboardHtml).toContain('id="revokeOperatorToken"');
  expect(dashboardHtml).toContain('id="inferenceQuotaForm"');
  expect(dashboardHtml).not.toContain("__LEANNAAUTO_");
 });
 it("exposes the shared spacing scale, semantic themes and accessible responsive controls",()=>{
  expect(dashboardHtml).toContain("--space-1:4px");
  expect(dashboardHtml).toContain("--space-16:64px");
  expect(dashboardHtml).toContain('html[data-theme="light"]');
  expect(dashboardHtml).toContain("prefers-reduced-motion:reduce");
  expect(dashboardHtml).toContain("focus-visible");
  expect(dashboardHtml).toContain('id="confirmOverlay"');
  expect(dashboardHtml).toContain('role="alertdialog"');
  expect(dashboardHtml).toContain('id="toastRegion"');
  expect(dashboardHtml).toContain("function confirmDialog(message)");
  expect(dashboardHtml).toContain("Jeton opérateur révoqué.");
  expect(dashboardHtml).toContain("Quota d’inférence mis à jour.");
  expect(dashboardHtml).not.toContain("confirm(");
  expect(dashboardHtml).not.toContain("alert(");
  expect(dashboardHtml).toContain("92dvh");
  expect(dashboardHtml).toContain('id="pageDescription"');
  expect(dashboardHtml).toContain('id="breadcrumbCurrent"');
  expect(dashboardHtml).toContain('class="nav-group-label"');
  expect(dashboardHtml).toContain("function initNavigationGroups()");
  expect(dashboardHtml).toContain("leanna_ui_nav_group_");
  expect(dashboardHtml).toContain('id="auditExport"');
  expect(dashboardHtml).toContain('id="auditActionFilter"');
  expect(dashboardHtml).toContain("function renderAudit()");
  expect(dashboardHtml).toContain("leanna-audit.csv");
  expect(dashboardHtml).not.toContain('id="auditOutput"');
  expect(dashboardHtml).toContain('id="eventLevelFilter"');
  expect(dashboardHtml).toContain('id="usageProgress"');
  expect(dashboardHtml).toContain("usagePercent=d.usage.quota>0");
  expect(dashboardHtml).toContain('data-task-view="kanban"');
  expect(dashboardHtml).toContain('data-agent-view="table"');
  expect(dashboardHtml).toContain('id="agentSort"');
  expect(dashboardHtml).toContain("let agentView='cards'");
  expect(dashboardHtml).toContain("task-kanban-column");
  expect(dashboardHtml).toContain("let taskView='table'");
  expect(dashboardHtml).toContain('role="log"');
  expect(dashboardHtml).toContain("event-details-toggle");
  expect(dashboardHtml).toContain("data-copy-event");
 });
 it("keeps every navigation target connected to a page section",()=>{
  const navigation=dashboardHtml.split('<nav aria-label="Navigation principale">')[1]?.split('</nav>')[0]??"";
  const pages=[...navigation.matchAll(new RegExp("page\\('([^']+)'","g"))].map(match=>match[1]);
  const sections=[...dashboardHtml.matchAll(new RegExp('<section\\b[^>]*id="([^"]+)"','g'))].map(match=>match[1]);
  expect(pages.length).toBeGreaterThan(0);
  expect(pages.every(page=>sections.includes(page))).toBe(true);
 });
 it("ships a syntactically valid browser client and unique static element IDs",()=>{
  const scriptStart=dashboardHtml.indexOf("<script>")+8;
  const scriptEnd=dashboardHtml.indexOf("</script>",scriptStart);
  const script=dashboardHtml.slice(scriptStart,scriptEnd);
  expect(scriptEnd).toBeGreaterThan(scriptStart);
  expect(()=>new Function(script)).not.toThrow();
  const markup=dashboardHtml.slice(0,dashboardHtml.indexOf("<script>"));
  const ids=[...markup.matchAll(new RegExp('\\bid="([^"]+)"','g'))].map(match=>match[1]);
  expect(new Set(ids).size).toBe(ids.length);
 });
});
